# A variable is created the moment you first assign a value to it.

# Strings & Integers

name = "Kush"
print(name)

name = "Kush"
print(f"Hello {name}")

name = "Kush"
hobby = "drawing"
age = 18

print(f"I am {name}")
print(f"My hobby is {hobby}")
print(f"My age is {age}")

# Float

price = 19.99
print(f"The price of potatoe chips is ${price:.2f}")

# Boolean

is_student = True
print(f"Is student: {is_student}")
